#!/usr/bin/env python3
"""Checks that AGENTS.md is still true.

A guide like AGENTS.md fails in a particular way: it drifts. It names a script that
was renamed, a check that moved, a stage count that changed — and then it misleads
exactly the people it exists to help, which is worse than not having it.

So the guide is verified against the repository rather than trusted.
"""

from __future__ import annotations

import pathlib
import re
import sys

root = pathlib.Path(__file__).resolve().parents[2]
guide_path = root / "AGENTS.md"

if not guide_path.exists():
    print("AGENTS.md is missing", file=sys.stderr)
    sys.exit(1)

guide = guide_path.read_text(encoding="utf-8")
problems: list[str] = []

# ---------------------------------------------------------------------------
# 1. Paths it tells you to touch must exist.
# ---------------------------------------------------------------------------

FILE_PATTERN = re.compile(
    r"`([A-Za-z0-9_./*-]+/[A-Za-z0-9_*.-]+"
    r"\.(?:rs|sh|py|swift|toml|yml|yaml|md|h|c|json|html|icns|png|svg|xcstrings))`"
)

# Artefacts that are generated, planned, or patterns rather than committed files.
EXPECTED_ABSENT = {
    "apps/mac/MacCV.xcodeproj",   # generated by xcodegen, deliberately not committed
    "assets/preview.gif",         # reserved for a future screencast
    # Written by the release workflow into the Pages artifact. Deliberately not
    # committed: a feed in the repository is a claim about a release that may not
    # have been published yet.
    "docs/latest.json",
    "docs/preview.json",
}
PATTERN_OK = ("*",)

for path in sorted(set(FILE_PATTERN.findall(guide))):
    if path in EXPECTED_ABSENT or any(token in path for token in PATTERN_OK):
        continue
    if not (root / path).exists():
        problems.append(f"names a path that does not exist: {path}")

# ---------------------------------------------------------------------------
# 2. Scripts it tells you to run must exist and be executable.
# ---------------------------------------------------------------------------

for script in sorted(set(re.findall(r"`(Scripts/[A-Za-z0-9_./-]+\.(?:sh|py))`", guide))):
    target = root / script
    if not target.exists():
        problems.append(f"references a missing script: {script}")
    elif not target.stat().st_mode & 0o111:
        problems.append(f"{script} is not executable, so the documented invocation fails")

# ---------------------------------------------------------------------------
# 3. The verify stage count must match, or the number misleads.
# ---------------------------------------------------------------------------

STAGE_PATTERN = re.compile(r'^\s*stage "', re.M)
actual_stages = len(STAGE_PATTERN.findall((root / "Scripts/verify.sh").read_text(encoding="utf-8")))

claimed = re.search(r"(\d+)\s+stages", guide)
if not claimed:
    problems.append("does not state the verify.sh stage count")
elif int(claimed.group(1)) != actual_stages:
    problems.append(
        f"claims {claimed.group(1)} verify stages but Scripts/verify.sh defines {actual_stages}"
    )

# ---------------------------------------------------------------------------
# 4. Every check it points at must exist.
# ---------------------------------------------------------------------------

for check in sorted(set(re.findall(r"`([a-z_]+\.py)`", guide))):
    if not (root / "Scripts" / "checks" / check).exists():
        problems.append(f"names a missing check: Scripts/checks/{check}")

# ---------------------------------------------------------------------------
# 5. The invariants table must name real enforcement mechanisms.
#
# An invariant with no check behind it is a claim, and the whole point of that
# section is to distinguish claims from enforcement.
# ---------------------------------------------------------------------------

in_invariants = False
for line in guide.splitlines():
    if line.startswith("## 5."):
        in_invariants = True
        continue
    if in_invariants and line.startswith("## 6."):
        break
    if not in_invariants or not line.startswith("|") or "---" in line:
        continue
    if not line.strip().startswith("| **"):
        continue
    # Every invariant row must reference something enforcing it.
    if not re.search(r"`[^`]+`", line.split("|")[2] if line.count("|") > 2 else line):
        problems.append(f"invariant has no enforcement mechanism: {line[:60]}…")

# ---------------------------------------------------------------------------
# 6. Sections referenced by the contents list must exist.
# ---------------------------------------------------------------------------

for number, title in re.findall(r"^\d+\. \[([^\]]+)\]\(#(\d+)-", guide, re.M):
    if not re.search(rf"^## {re.escape(title.split()[0])}\.", guide, re.M) and \
       not re.search(rf"^## \d+\. {re.escape(' '.join(title.split()[:2]))}", guide, re.M):
        # The anchor format is "#3-the-coupled-files-map"; check the heading exists.
        slug = re.sub(r"[^a-z0-9 ]", "", title.lower()).replace(" ", "-")
        if slug.split("-")[0] not in guide.lower():
            problems.append(f"contents entry points at a missing section: {title}")

# ---------------------------------------------------------------------------

print(f"  {len(set(FILE_PATTERN.findall(guide)))} paths and {actual_stages} verify stages cross-checked")

if problems:
    for problem in sorted(set(problems)):
        print(f"  {problem}", file=sys.stderr)
    sys.exit(1)

print("  AGENTS.md is consistent with the repository")
